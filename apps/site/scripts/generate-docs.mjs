import { access, mkdir, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const packageRoot = path.resolve(import.meta.dirname, '..');
const docsDir = path.join(packageRoot, 'docs');
const outputFile = path.join(
  packageRoot,
  'source',
  'docs',
  'generated',
  'demos.ts',
);
const ignoredDirectories = new Set(['assets', 'node_modules']);

async function exists(filePath) {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function findDemoIndexes(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const indexes = [];

  for (const entry of entries) {
    if (!entry.isDirectory() || entry.name.startsWith('.')) {
      continue;
    }

    const entryPath = path.join(directory, entry.name);

    if (entry.name === 'demos') {
      for (const fileName of ['index.ts', 'index.tsx']) {
        const indexFile = path.join(entryPath, fileName);

        if (await exists(indexFile)) {
          indexes.push({
            base: path.relative(docsDir, directory),
            indexFile,
          });
          break;
        }
      }

      continue;
    }

    if (ignoredDirectories.has(entry.name)) {
      continue;
    }

    indexes.push(...(await findDemoIndexes(entryPath)));
  }

  return indexes;
}

function identifier(base) {
  const normalized = base.replace(/[^a-zA-Z0-9]+/g, '_') || 'root';
  return `demo_${normalized}`;
}

const demos = (await findDemoIndexes(docsDir)).sort((first, second) =>
  first.base.localeCompare(second.base, 'en'),
);

const imports = demos.map(({ base, indexFile }) => {
  const relative = path
    .relative(path.dirname(outputFile), indexFile)
    .replace(/\\/g, '/')
    .replace(/\/index\.tsx?$/, '');

  return `import * as ${identifier(base)} from '${relative}';`;
});

const entries = demos.map(
  ({ base }) => `  '${base.replace(/\\/g, '/')}': ${identifier(base)},`,
);

const output = [
  '// This file is generated by scripts/generate-docs.mjs.',
  '// Run `pnpm --filter @one/site generate:docs` after adding or removing demos.',
  '',
  "import type { ComponentType } from 'react';",
  '',
  ...imports,
  '',
  'export const demoModules: Record<string, Record<string, ComponentType>> = {',
  ...entries,
  '};',
  '',
].join('\n');

await mkdir(path.dirname(outputFile), { recursive: true });
await writeFile(outputFile, output);

console.log(
  `Generated ${path.relative(packageRoot, outputFile)} with ${demos.length} demo ${
    demos.length === 1 ? 'group' : 'groups'
  }.`,
);
